export const BY_ISO = new Map(COUNTRIES.map((c) => [c[1], c]));

/** Regional-indicator flag emoji from an ISO-2 code. No image files needed. */
export function flag(iso) {
  if (!iso || iso.length !== 2) return "🏳️";
  const upper = iso.toUpperCase();
  if (upper === "XK") return "🇽🇰";
  return String.fromCodePoint(
    ...[...upper].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65)
  );
}

export function nameOf(iso) {
  const c = BY_ISO.get(iso);
  return c ? c[0] : iso;
}

export function popOf(iso) {
  const c = BY_ISO.get(iso);
  return c ? c[2] : 0;
}
